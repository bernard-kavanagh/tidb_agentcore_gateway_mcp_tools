"""Tamper-evident hash chain for the append-only fact_event log.

Scope: PER-SUBJECT. Each event links to the previous event *for the same
subject_id*. The first event for a subject links to GENESIS_HASH.

`event_hash = sha256( canonical(event fields) || prev_hash )`.

The exact same canonicalization must be used by the write path and the
verifier, so both live here and nowhere else. event_id and the DB-side
defaults are deliberately NOT part of the hash: event_id is AUTO_RANDOM
(unknown before insert) and observed_at is generated by the handler and
passed in explicitly so it is deterministic and hashable.
"""

from __future__ import annotations

import hashlib
import json
from decimal import Decimal
from typing import Any, Iterable

# Genesis link for the first event of a subject's chain (64 hex zeros).
GENESIS_HASH = "0" * 64

# Field order is fixed by sorting keys in the canonical JSON, so the physical
# order below is irrelevant — but every hashed field is listed here as the
# single source of truth for what the chain commits to.
HASHED_FIELDS = (
    "subject_id",
    "tenant_id",
    "op",
    "value",
    "source",
    "confidence",
    "agent_id",
    "session_id",
    "tool_turn",
    "supersedes_event_id",
    "observed_at",
    "prev_hash",
)


def canonical_json(obj: Any) -> str:
    """Deterministic JSON: sorted keys, no whitespace, UTF-8 preserved."""
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def _normalize_confidence(confidence: Any) -> str | None:
    """DECIMAL(4,3) -> a stable 3dp string so float/Decimal/str all hash equally."""
    if confidence is None:
        return None
    return str(Decimal(str(confidence)).quantize(Decimal("0.001")))


def _canonical_payload(fields: dict[str, Any]) -> dict[str, Any]:
    """Coerce the hashed fields into JSON-stable primitives."""
    return {
        "subject_id": int(fields["subject_id"]),
        "tenant_id": str(fields["tenant_id"]),
        "op": str(fields["op"]),
        # `value` is arbitrary JSON; canonical_json on the whole payload
        # (sort_keys) canonicalizes nested objects too.
        "value": fields["value"],
        "source": str(fields["source"]),
        "confidence": _normalize_confidence(fields.get("confidence")),
        "agent_id": str(fields["agent_id"]),
        "session_id": str(fields["session_id"]),
        "tool_turn": None if fields.get("tool_turn") is None else int(fields["tool_turn"]),
        "supersedes_event_id": (
            None if fields.get("supersedes_event_id") is None
            else int(fields["supersedes_event_id"])
        ),
        # observed_at must arrive as a stable ISO-8601 string (UTC, microseconds).
        "observed_at": str(fields["observed_at"]),
        "prev_hash": str(fields["prev_hash"]),
    }


def compute_event_hash(fields: dict[str, Any]) -> str:
    """sha256 over the canonical hashed payload (which already includes prev_hash)."""
    payload = _canonical_payload(fields)
    return hashlib.sha256(canonical_json(payload).encode("utf-8")).hexdigest()


def verify_chain(events: Iterable[dict[str, Any]]) -> tuple[bool, list[str]]:
    """Verify a single subject's per-subject chain.

    `events` is the set of that subject's events (any order); each dict carries
    the stored hashed fields plus `event_hash` and `prev_hash`.

    Checks, in order:
      1. every stored event_hash recomputes from its own fields + prev_hash
         (content integrity — nothing was mutated in place);
      2. the events form a single unbroken chain from GENESIS with no fork,
         gap, or orphan (structural integrity).
    """
    events = list(events)
    errors: list[str] = []
    if not events:
        return True, errors

    # 1. Content integrity.
    for ev in events:
        recomputed = compute_event_hash(ev)
        if recomputed != ev["event_hash"]:
            errors.append(
                f"event_id={ev.get('event_id')} content hash mismatch: "
                f"stored={ev['event_hash']} recomputed={recomputed}"
            )

    # 2. Structural integrity: follow prev_hash links from genesis.
    by_prev: dict[str, list[dict[str, Any]]] = {}
    for ev in events:
        by_prev.setdefault(ev["prev_hash"], []).append(ev)

    roots = by_prev.get(GENESIS_HASH, [])
    if len(roots) != 1:
        errors.append(f"expected exactly one genesis-rooted event, found {len(roots)}")
        return False, errors

    seen = 0
    cursor = roots[0]
    while cursor is not None:
        seen += 1
        nexts = by_prev.get(cursor["event_hash"], [])
        if len(nexts) > 1:
            errors.append(
                f"chain fork after event_hash={cursor['event_hash']}: "
                f"{len(nexts)} successors"
            )
            return False, errors
        cursor = nexts[0] if nexts else None

    if seen != len(events):
        errors.append(
            f"chain covers {seen} events but {len(events)} exist "
            "(gap, orphan, or duplicate prev_hash)"
        )

    return (len(errors) == 0), errors
